package com.collabcode.execution.model;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;

/**
 * Run request body – T-17 V2.8 (Decision 8).
 *
 * Required fields: request_id, room_id, session_id, language, source.
 * Optional field:  stdin (defaults to "" when absent).
 *
 * The legacy 'code' field is no longer accepted: any request body with 'code'
 * is rejected as INVALID_REQUEST (HTTP 422).
 */
public class RunRequest {

    public static final String UUID_V4_REGEX =
            "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-4[0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$";

    /** UUID v4 generated by the client. Echoed in the response. */
    @NotBlank(message = "request_id is required")
    @Pattern(regexp = UUID_V4_REGEX, message = "request_id must be a UUID v4")
    private String request_id;

    /** The room the result is delivered to. */
    @NotBlank(message = "room_id is required")
    private String room_id;

    /** Stable per-browser session id. Caller's private credential. */
    @NotBlank(message = "session_id is required")
    @Pattern(regexp = UUID_V4_REGEX, message = "session_id must be a UUID v4")
    private String session_id;

    /**
     * Language identifier (DR1).
     * Accepted values: cpp, python, c, java, javascript.
     */
    @NotBlank(message = "language is required")
    private String language;

    /** Standard input; defaults to "". */
    private String stdin = "";

    /**
     * Exactly one source object: inline or saved (T-17 V2.8).
     */
    private RunSource source;

    /**
     * Legacy v0 field. If present in request body (even if null), rejected with 422 INVALID_REQUEST.
     */
    private boolean codeFieldPresent = false;
    private String code;

    // ----- getters and setters -----

    public String getRequest_id() { return request_id; }
    public void setRequest_id(String request_id) { this.request_id = request_id; }

    public String getRoom_id() { return room_id; }
    public void setRoom_id(String room_id) { this.room_id = room_id; }

    public String getSession_id() { return session_id; }
    public void setSession_id(String session_id) { this.session_id = session_id; }

    public String getLanguage() { return language; }
    public void setLanguage(String language) { this.language = language; }

    public String getStdin() { return stdin; }
    public void setStdin(String stdin) { this.stdin = (stdin != null) ? stdin : ""; }

    public RunSource getSource() { return source; }
    public void setSource(RunSource source) { this.source = source; }

    public String getCode() { return code; }

    @com.fasterxml.jackson.annotation.JsonProperty("code")
    public void setCode(com.fasterxml.jackson.databind.JsonNode node) {
        this.codeFieldPresent = true;
        this.code = (node != null && !node.isNull()) ? node.asText() : null;
    }

    public void setCodeText(String code) {
        this.codeFieldPresent = (code != null);
        this.code = code;
    }

    public boolean hasCodeField() { return codeFieldPresent; }
}
