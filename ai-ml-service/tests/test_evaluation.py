"""Unit and integration tests for baseline anomaly model evaluation (T-15).

deliverables for issue T-15:
- Single-call scoring function returns a float in [0.0, 1.0].
- Directional sanity check: anomalous runs score higher than normal runs.
- Reproducibility: same seed produces identical evaluation results.
- Evaluation on held-out synthetic test set achieves high ROC-AUC separation.
"""

import os
import sys
from pathlib import Path
import pytest

# Ensure ai-ml-service root is in sys.path
SERVICE_ROOT = Path(__file__).resolve().parent.parent
if str(SERVICE_ROOT) not in sys.path:
    sys.path.insert(0, str(SERVICE_ROOT))

from app.ml.scorer import AnomalyScorer
from scripts.evaluate_baseline import evaluate_model


@pytest.fixture(scope="module")
def scorer():
    """Returns an instance of AnomalyScorer with the trained baseline model."""
    model_path = os.path.join(SERVICE_ROOT, "models/baseline_anomaly_model.joblib")
    return AnomalyScorer(model_path=model_path)


def test_scorer_single_call_returns_valid_float(scorer):
    """AC 5: The scoring step works on one run's features in a single call and returns a float."""
    sample_run = {
        "execution_time_ms": 320.0,
        "peak_memory_mb": 15.5,
        "stdout_bytes": 1024,
        "stderr_bytes": 0,
        "exit_code": 0,
        "timed_out": False,
        "oom_killed": False,
    }

    score = scorer.score_run(sample_run)

    assert isinstance(score, float)
    assert 0.0 <= score <= 1.0


def test_sanity_check_anomalous_scores_higher_than_normal(scorer):
    """DoD & AC 2: A clearly anomalous run scores strictly higher than a clearly normal run."""
    normal_run = {
        "execution_time_ms": 150.0,
        "peak_memory_mb": 12.0,
        "stdout_bytes": 100,
        "stderr_bytes": 0,
        "exit_code": 0,
        "timed_out": False,
        "oom_killed": False,
    }

    # Test against multiple anomaly types from T-13
    anomalous_timeout = {
        "execution_time_ms": 5000.0,
        "peak_memory_mb": 25.0,
        "stdout_bytes": 50,
        "stderr_bytes": 0,
        "exit_code": 137,
        "timed_out": True,
        "oom_killed": False,
    }

    anomalous_memory = {
        "execution_time_ms": 1200.0,
        "peak_memory_mb": 125.0,
        "stdout_bytes": 0,
        "stderr_bytes": 0,
        "exit_code": 137,
        "timed_out": False,
        "oom_killed": True,
    }

    anomalous_output = {
        "execution_time_ms": 600.0,
        "peak_memory_mb": 30.0,
        "stdout_bytes": 950000,
        "stderr_bytes": 0,
        "exit_code": 0,
        "timed_out": False,
        "oom_killed": False,
    }

    normal_score = scorer.score_run(normal_run)
    timeout_score = scorer.score_run(anomalous_timeout)
    memory_score = scorer.score_run(anomalous_memory)
    output_score = scorer.score_run(anomalous_output)

    assert timeout_score > normal_score, f"Timeout score ({timeout_score}) must exceed normal ({normal_score})"
    assert memory_score > normal_score, f"Memory spike score ({memory_score}) must exceed normal ({normal_score})"
    assert output_score > normal_score, f"Output flood score ({output_score}) must exceed normal ({normal_score})"


def test_reproducibility_evaluation_metrics():
    """DoD: Two evaluation runs on the same dataset/seed yield identical metrics."""
    test_path = os.path.join(SERVICE_ROOT, "models/test_set.csv")
    model_path = os.path.join(SERVICE_ROOT, "models/baseline_anomaly_model.joblib")

    if not os.path.exists(test_path):
        pytest.skip("Test dataset not yet generated by conftest")

    eval_1 = evaluate_model(test_data_path=test_path, model_path=model_path, seed=42)
    eval_2 = evaluate_model(test_data_path=test_path, model_path=model_path, seed=42)

    assert eval_1["roc_auc"] == eval_2["roc_auc"]
    assert eval_1["pr_auc"] == eval_2["pr_auc"]
    assert eval_1["normal_mean_score"] == eval_2["normal_mean_score"]
    assert eval_1["anomalous_mean_score"] == eval_2["anomalous_mean_score"]
    assert eval_1["score_separation_margin"] == eval_2["score_separation_margin"]


def test_evaluation_achieves_strong_separation_on_synthetic_data():
    """AC 3: Baseline model reliably separates normal from anomalous synthetic rows."""
    test_path = os.path.join(SERVICE_ROOT, "models/test_set.csv")
    model_path = os.path.join(SERVICE_ROOT, "models/baseline_anomaly_model.joblib")

    if not os.path.exists(test_path):
        pytest.skip("Test dataset not yet generated by conftest")

    results = evaluate_model(test_data_path=test_path, model_path=model_path, seed=42)

    # ROC-AUC should be very high (> 0.95) on the synthetic dataset with clean class bounds
    assert results["roc_auc"] >= 0.95, f"Expected ROC-AUC >= 0.95 on synthetic data, got {results['roc_auc']}"
    assert results["sanity_check_passed"] is True
    assert results["anomalous_mean_score"] > results["normal_mean_score"]
